"""Documented Lumerical FDTD project construction and numerical acceptance gates."""

import importlib
import json
from pathlib import Path
import sys

import numpy as np
from scipy.integrate import trapezoid

from metasurface.reduced.geometry import rectangles
from metasurface.common.storage import canonical_json, load_npz, save_npz

C0 = 299792458.0
EPS0 = 8.8541878128e-12


def _solver_log_paths(project_path):
    """Return the documented per-process logs for a saved Lumerical project.

    Args:
        project_path (Path-like): Saved ``.fsp`` project passed to the engine.

    Returns:
        list[Path]: Existing ``<project stem>_p*.log`` files in process order.
    """
    project = Path(project_path)
    return sorted(project.parent.glob(f"{project.stem}_p*.log"))


def check_solver_log(project_path):
    """Raise with a native FDTD engine diagnostic when its log reports a crash.

    Args:
        project_path (Path-like): Saved ``.fsp`` project passed to the engine.

    Returns:
        None.

    Raises:
        RuntimeError: If a process log contains a native fatal diagnostic.

    Notes:
        Lumerical writes ``<project stem>_p0.log`` beside the project. Missing
        logs are left to the Automation API because some resource setups route
        logs elsewhere.
    """
    fatal_markers = (
        "invalid unordered_map",
        "fatal error",
        "terminate called",
        "unhandled exception",
        "solver exited unexpectedly",
        "cuda error",
    )
    for path in _solver_log_paths(project_path):
        text = path.read_text(errors="replace")
        lines = [line.strip() for line in text.splitlines() if line.strip()]
        for line in reversed(lines):
            if any(marker in line.lower() for marker in fatal_markers):
                raise RuntimeError(f"Lumerical FDTD engine failed ({path.name}): {line}")


def run_on_gpu(sim, project_path=None):
    """Check and launch one Lumerical FDTD solve explicitly on GPU.

    Args:
        sim: Active ``lumapi.FDTD`` session containing a constructed project.

    Returns:
        None.

    Raises:
        RuntimeError: If GPU compatibility checking or GPU execution fails.

    Notes:
        There is deliberately no CPU fallback. The two explicit arguments to
        ``run`` override the resource type selected in the Lumerical GUI.
    """
    try:
        sim.runsystemcheck("FDTD", "GPU")
        sim.run("FDTD", "GPU")
    except Exception as error:
        if project_path is not None:
            check_solver_log(project_path)
        raise RuntimeError(
            "GPU-required Lumerical FDTD execution failed. Configure an active "
            f"GPU resource and ensure this project is GPU-compatible. API error: {error}"
        ) from error
    if project_path is not None:
        check_solver_log(project_path)


def validate_physics(p):
    """Reject physical configurations incompatible with this normal-incidence model.

    Args:
        p (dict): Simulation settings from config.py.
    Returns:
        None.
    Raises:
        ValueError: If lengths, band, material, or monitor placement are invalid.
    Notes:
        Below the first air diffraction order, plane-averaged fields describe
        the reflected propagating channels. This exporter supports that regime.
    """
    if any(not np.isfinite(v) for v in p.values() if isinstance(v, (int, float))):
        raise ValueError("Physical settings must be finite.")
    positive = ["pixel_m", "substrate_thickness_m", "metal_thickness_m", "mesh_xy_m", "mesh_z_m",
                "simulation_time_s", "frequency_min_hz", "copper_conductivity_s_m"]
    if any(p[k] <= 0 for k in positive) or p["frequency_points"] < 10:
        raise ValueError("Lengths, time, conductivity, and frequency must be positive.")
    if p["frequency_max_hz"] <= p["frequency_min_hz"]:
        raise ValueError("Invalid frequency band.")
    if p["frequency_max_hz"] >= C0 / (32 * p["pixel_m"]):
        raise ValueError("The requested band reaches the first air diffraction order.")
    if p["metal_model"] not in ("copper", "pec") or p["epsilon_imag"] < 0 or p["epsilon_real"] < 1:
        raise ValueError("Unsupported metal or substrate material.")
    if not (p["z_min_m"] < -p["substrate_thickness_m"] - p["metal_thickness_m"] < 0
            < p["metal_thickness_m"] < p["incident_z_m"] < p["source_z_m"]
            < p["reflection_z_m"] < p["z_max_m"]):
        raise ValueError("Invalid layer/source/monitor ordering.")


def rectangle_script(name, x, y, dx, dy, z_min, z_max, material):
    """Emit a rectangle object in Lumerical's SI scripting language.

    Args:
        name (str): Object name generated by this package.
        x (float): Center x coordinate in metres.
        y (float): Center y coordinate in metres.
        dx (float): x span in metres.
        dy (float): y span in metres.
        z_min (float): Bottom face coordinate in metres.
        z_max (float): Top face coordinate in metres.
        material (str): Database material name.
    Returns:
        str: Standalone object creation commands.
    Raises:
        None.
    """
    return (f'addrect; set("name","{name}"); set("x",{x:.12g}); set("y",{y:.12g}); '
            f'set("x span",{dx:.12g}); set("y span",{dy:.12g}); '
            f'set("z min",{z_min:.12g}); set("z max",{z_max:.12g}); set("material","{material}");\n')


def project_script(codes, physics, reference="device", rectangle_fn=rectangles):
    """Build a self-contained LSF project for a device, empty space, or PEC mirror.

    Args:
        codes (array-like): Four independent pattern IDs.
        physics (dict): SI material, mesh, source, and simulation settings.
        reference (str): 'device', 'empty', or 'mirror'.
        rectangle_fn (callable): Family-specific SI rectangle builder.
    Returns:
        str: LSF commands constructing a ready-to-save layout, without running it.
    Raises:
        ValueError: If geometry, physics, or reference mode is invalid.
    Notes:
        Execute in a fresh project. The script clears objects and owns two
        named materials. Normal incidence uses x polarization and propagation -z.
    Examples:
        Path('build_project.lsf').write_text(project_script([1, 2, 3, 0], PHYSICS))
    """
    validate_physics(physics)
    objects = rectangle_fn(codes, physics["pixel_m"])
    if reference not in ("device", "empty", "mirror"):
        raise ValueError("Invalid reference mode.")
    p = physics
    period = 32 * p["pixel_m"]
    h = p["substrate_thickness_m"]
    t = p["metal_thickness_m"]
    pec = "PEC (Perfect Electrical Conductor)"
    metal = "Copper_RF" if p["metal_model"] == "copper" else pec
    fmin, fmax = p["frequency_min_hz"], p["frequency_max_hz"]
    script = f'''# Generated metasurface. All dimensions use SI units.
switchtolayout; selectall; delete;
if(materialexists("FR4_RF")) {{ deletematerial("FR4_RF"); }}
if(materialexists("Copper_RF")) {{ deletematerial("Copper_RF"); }}
mat=addmaterial("Sampled data"); setmaterial(mat,"name","FR4_RF");
mf=linspace({fmin:.12g},{fmax:.12g},101);
meps=({p['epsilon_real']:.12g}+1i*{p['epsilon_imag']:.12g})*ones(101,1);
setmaterial("FR4_RF","max coefficients",8);
setmaterial("FR4_RF","tolerance",0.001);
setmaterial("FR4_RF","sampled data",[mf,meps]);
mat=addmaterial("Sampled data"); setmaterial(mat,"name","Copper_RF");
ceps=1+1i*{p['copper_conductivity_s_m'] / (2 * np.pi * EPS0):.12g}/mf;
setmaterial("Copper_RF","max coefficients",8);
setmaterial("Copper_RF","tolerance",0.001);
setmaterial("Copper_RF","sampled data",[mf,ceps]);
addfdtd; set("dimension","3D");
set("x",0); set("y",0); set("x span",{period:.12g}); set("y span",{period:.12g});
set("z min",{p['z_min_m']:.12g}); set("z max",{p['z_max_m']:.12g});
set("x min bc","Periodic"); set("x max bc","Periodic");
set("y min bc","Periodic"); set("y max bc","Periodic");
set("z min bc","PML"); set("z max bc","PML");
set("simulation time",{p['simulation_time_s']:.12g});
set("auto shutoff min",{p['autoshutoff']:.12g});
addmesh; set("name","cell_mesh"); set("x",0); set("y",0);
set("x span",{period:.12g}); set("y span",{period:.12g});
set("z min",{-h-t:.12g}); set("z max",{t:.12g});
set("override x mesh",1); set("override y mesh",1); set("override z mesh",1);
set("dx",{p['mesh_xy_m']:.12g}); set("dy",{p['mesh_xy_m']:.12g}); set("dz",{p['mesh_z_m']:.12g});
addplane; set("name","source"); set("injection axis","z"); set("direction","Backward");
set("x",0); set("y",0); set("x span",{period:.12g}); set("y span",{period:.12g});
set("z",{p['source_z_m']:.12g}); set("angle theta",0); set("angle phi",0); set("polarization angle",0);
set("override global source settings",1);
set("wavelength start",{C0/fmax:.12g}); set("wavelength stop",{C0/fmin:.12g});
setglobalmonitor("use source limits",1); setglobalmonitor("use linear wavelength spacing",0);
setglobalmonitor("frequency points",{p['frequency_points']});
'''
    for name, z in [("incident", p["incident_z_m"]), ("reflection", p["reflection_z_m"])]:
        script += (f'addpower; set("name","{name}"); set("monitor type","2D Z-normal"); '
                   f'set("x",0); set("y",0); set("x span",{period:.12g}); set("y span",{period:.12g}); set("z",{z:.12g});\n')
    if reference == "mirror":
        script += rectangle_script("mirror", 0, 0, period, period, 0, t, pec)
    if reference == "device":
        script += rectangle_script("substrate", 0, 0, period, period, -h, 0, "FR4_RF")
        script += rectangle_script("ground", 0, 0, period, period, -h - t, -h, metal)
        for i, (x, y, dx, dy) in enumerate(objects):
            script += rectangle_script(f"pixel_{i}", x, y, dx, dy, 0, t, metal)
        if p["metal_model"] == "copper":
            # Resolve thickness and check absorption through refinement, rather
            # than assuming an optical copper database remains valid in GHz.
            for name, bottom, top in [("top", 0, t), ("ground", -h - t, -h)]:
                dz = t / p.get("metal_mesh_divisions", 3)
                script += (f'addmesh; set("name","copper_mesh_{name}"); set("x",0); set("y",0); '
                           f'set("x span",{period:.12g}); set("y span",{period:.12g}); '
                           f'set("z min",{bottom:.12g}); set("z max",{top:.12g}); '
                           f'set("override x mesh",0); set("override y mesh",0); set("override z mesh",1); set("dz",{dz:.12g});\n')
    return script


def check_status(status):
    """Require solver termination by energy decay, not by the time limit.

    Args:
        status (number): Lumerical status, where 2 denotes autoshutoff.
    Returns:
        None.
    Raises:
        RuntimeError: If the run diverged, timed out, or did not finish.
    """
    if int(np.asarray(status).item()) != 2:
        raise RuntimeError("FDTD did not reach autoshutoff. Increase time or diagnose divergence.")


def check_pulse(spectrum, minimum):
    """Check actual source pulse energy coverage across the analysis band.

    Args:
        spectrum (array-like): Complex sourcenorm spectrum, not CW sourcepower.
        minimum (float): Required minimum power relative to the spectral maximum.
    Returns:
        ndarray: Relative pulse power at each frequency.
    Raises:
        RuntimeError: If excitation is absent, nonfinite, or too weak.
    """
    power = np.abs(np.asarray(spectrum).reshape(-1))**2
    if not np.isfinite(power).all() or not len(power) or power.max() <= 0:
        raise RuntimeError("Invalid source excitation spectrum.")
    relative = power / power.max()
    if relative.min() < minimum:
        raise RuntimeError("Weak source excitation at frequency edges. Narrow or extend the source band.")
    return relative


def mean_field(values, count):
    """Average a complex field while retaining its final frequency dimension.

    Args:
        values (array-like): Field array with frequency as its last axis.
        count (int): Expected frequency count.
    Returns:
        ndarray: Complex vector of shape (count,).
    Raises:
        ValueError: If axes or values are invalid.
    Notes:
        This shape helper is used in contract tests. Physical monitor data use
        spatial quadrature in plane_field to account for nonuniform meshes.
    """
    values = np.asarray(values)
    if values.ndim < 1 or values.shape[-1] != count or not np.isfinite(values).all():
        raise ValueError("Invalid field frequency axis or nonfinite monitor data.")
    return values.reshape(-1, count).mean(axis=0)


def plane_field(result, component):
    """Integrate a plane monitor field over its actual x and y coordinates.

    Args:
        result (dict): Lumerical rectilinear E dataset.
        component (str): 'Ex' or 'Ey'.
    Returns:
        ndarray: Spatially averaged complex field for each frequency.
    Raises:
        ValueError: If monitor coordinates or field dimensions are invalid.
    """
    x = np.asarray(result["x"]).reshape(-1)
    y = np.asarray(result["y"]).reshape(-1)
    n = len(np.asarray(result["f"]).reshape(-1))
    if component not in ("Ex", "Ey"):
        raise ValueError("Only Ex and Ey plane components are supported.")
    vector = np.asarray(result["E"])
    if vector.shape != (len(x), len(y), 1, n, 3):
        raise ValueError("Unexpected Lumerical vector E dataset dimensions.")
    field = vector[..., 0 if component == "Ex" else 1]
    if field.shape != (len(x), len(y), 1, n) or not np.isfinite(field).all():
        raise ValueError("Unexpected plane monitor field shape or invalid values.")
    if len(x) < 2 or len(y) < 2 or np.any(np.diff(x) <= 0) or np.any(np.diff(y) <= 0):
        raise ValueError("Plane coordinates must span a strictly increasing mesh.")
    integral_x = trapezoid(field[:, :, 0, :], x=x, axis=0)
    return trapezoid(integral_x, x=y, axis=0) / ((x[-1] - x[0]) * (y[-1] - y[0]))


class LumericalSolver:
    """Run licensed FDTD projects with shared reference normalization."""

    def __init__(self, physics, rectangle_fn=rectangles, code_count=4):
        """Record validated settings without loading the proprietary API yet.

        Args:
            physics (dict): Simulation configuration.
            rectangle_fn (callable): Family-specific SI rectangle builder.
            code_count (int): Tile-code count for preflight references.
        Returns:
            None.
        Raises:
            ValueError: If settings are incompatible with this model.
        """
        validate_physics(physics)
        self.physics = dict(physics)
        self.rectangle_fn = rectangle_fn
        self.code_count = code_count
        self.reference = None
        self.directory = None

    def _run(self, codes, reference="device", project_path=None):
        """Execute one fresh project and return accepted monitor arrays.

        Args:
            codes (array-like): Four independent pattern choices.
            reference (str): Device, empty, or mirror mode.
            project_path (Path-like or None): Optional saved .fsp project.
        Returns:
            dict: Sorted frequencies, averaged fields, and total reflection.
        Raises:
            RuntimeError: If API loading, material fit, or numerical gates fail.
            ValueError: If monitor data are malformed.
        """
        import metasurface.config as config

        api_dir = str(config.LUMAPI_DIR)
        if not (Path(api_dir) / "lumapi.py").exists():
            raise RuntimeError("Set LUMAPI_DIR in config.py to the installed Lumerical Python API.")
        if api_dir not in sys.path:
            sys.path.insert(0, api_dir)
        lumapi = importlib.import_module("lumapi")
        p = self.physics
        expected = np.linspace(p["frequency_min_hz"], p["frequency_max_hz"], p["frequency_points"])
        if project_path is None:
            if self.directory is None:
                raise RuntimeError("Set a solver directory before running an unnamed project.")
            project_path = self.directory / "active_device.fsp"
        with lumapi.FDTD(hide=True) as sim:
            sim.eval(project_script(codes, p, reference, self.rectangle_fn))
            fitted = np.asarray(sim.getfdtdindex("FR4_RF", expected, expected[0], expected[-1])).reshape(-1)**2
            target = p["epsilon_real"] + 1j * p["epsilon_imag"]
            if len(fitted) != len(expected) or not np.isfinite(fitted).all() or np.max(abs(fitted - target)) > p["material_fit_tolerance"]:
                raise RuntimeError("FR4 material fit does not reproduce the specified complex permittivity.")
            sim.save(str(Path(project_path).resolve()))
            run_on_gpu(sim, project_path)
            check_status(sim.getresult("FDTD", "status"))
            reflection = sim.getresult("reflection", "E")
            incident = sim.getresult("incident", "E")
            f = np.asarray(reflection["f"]).reshape(-1)
            order = np.argsort(f)
            if len(f) != len(expected) or not np.allclose(f[order], expected, rtol=1e-8, atol=1):
                raise ValueError("Monitor frequency band does not match the configured band.")
            if not np.allclose(np.asarray(incident["f"]).reshape(-1), f, rtol=1e-8):
                raise ValueError("Monitor frequency grids differ.")
            total = np.asarray(sim.transmission("reflection")).reshape(-1)[order]
            output = {"frequencies": f[order], "incident": plane_field(incident, "Ex")[order],
                      "ex": plane_field(reflection, "Ex")[order], "ey": plane_field(reflection, "Ey")[order],
                      "total": total}
            # Validate the pulse from the recorded incident field.  Lumerical
            # 2025 R2 rejects sourcenorm before a solve, while the monitor is
            # the actual excitation delivered across the requested band.
            if reference == "empty":
                check_pulse(output["incident"], p["minimum_pulse_power"])
            # Keep the pre-run construction project small and reproducible.
            # Raw monitor results are returned to the NPZ checkpoint; saving
            # the solved project here produced multi-gigabyte files and a
            # native lumapi crash when the session was closed on Windows.
        return output

    def _powers(self, raw):
        """Normalize reflected fields against the stored empty-space incident run.

        Args:
            raw (dict): Fields returned by _run.
        Returns:
            dict: Co-polarized, cross-polarized, and total power spectra.
        Raises:
            RuntimeError: If calibration is missing or channel power disagrees.
        """
        if self.reference is None:
            raise RuntimeError("Run preflight before simulating devices.")
        incident = np.abs(self.reference["incident"])**2
        if not np.isfinite(incident).all() or np.any(incident < 1e-12):
            raise RuntimeError("Invalid incident reference field.")
        co = abs(raw["ex"] - self.reference["ex"])**2 / incident
        cross = abs(raw["ey"] - self.reference["ey"])**2 / incident
        total = raw["total"]
        if not np.isfinite(total).all() or np.any(total < -1e-5) or np.any(total > 1.05):
            raise RuntimeError("Nonphysical reflected flux.")
        total = np.maximum(total, 0)
        if np.max(abs(co + cross - total)) > 0.05:
            raise RuntimeError("Field-derived and flux-derived reflection disagree. Check monitors and convergence.")
        return {"co": co, "cross": cross, "total": total}

    def preflight(self, directory, mode="full"):
        """Calibrate references and verify representative mesh/time convergence.

        Args:
            directory (Path-like): Directory storing reusable reference evidence.
        Returns:
            None.
        Raises:
            RuntimeError: If calibration or convergence checks fail.
            ValueError: If saved references belong to another configuration.
        Notes:
            Preflight covers one representative geometry. Final designs still
            require their own convergence checks for quantitative claims.
        """
        if mode not in ("full", "reference_only"):
            raise ValueError("Preflight mode must be 'full' or 'reference_only'.")
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        self.directory = directory
        signature = canonical_json(self.physics)
        if mode == "reference_only":
            path = directory / "physical_reference.npz"
            if path.exists():
                reference = load_npz(path)
                if (reference["physics"].item() != signature
                        or reference["mode"].item() != mode):
                    raise ValueError("Saved physical reference configuration mismatch.")
                self.reference = reference
                print("Reference only: accepted saved empty-space calibration; validation skipped", flush=True)
                return
            print("Reference only: empty-space calibration (physical validation skipped)", flush=True)
            raw = self._run([0] * self.code_count, "empty", directory / "reference_empty.fsp")
            if np.max(abs(raw["total"])) > 0.01:
                raise RuntimeError("Empty-space reflection calibration exceeds 1%.")
            record = {**raw, "physics": np.asarray(signature), "mode": np.asarray(mode)}
            save_npz(path, record)
            self.reference = record
            print("Reference only: calibration saved; PEC and convergence gates skipped", flush=True)
            return
        path = directory / "physical_preflight.npz"
        if path.exists():
            reference = load_npz(path)
            if reference["physics"].item() != signature or not bool(reference["passed"].item()):
                raise ValueError("Saved physical preflight configuration mismatch.")
            self.reference = reference
            print("Preflight: accepted saved reference and convergence evidence", flush=True)
            return
        print("Preflight: empty reference", flush=True)
        raw = self._run([0] * self.code_count, "empty", directory / "reference_empty.fsp")
        if np.max(abs(raw["total"])) > 0.01:
            raise RuntimeError("Empty-space reflection calibration exceeds 1%.")
        self.reference = raw
        print("Preflight: PEC mirror", flush=True)
        mirror = self._powers(self._run([0] * self.code_count, "mirror", directory / "reference_pec.fsp"))
        if np.max(abs(mirror["co"] - 1)) > 0.05 or np.max(mirror["cross"]) > 0.01:
            raise RuntimeError("PEC mirror does not reproduce unit co-polarized reflection.")
        print("Preflight: coarse pilot", flush=True)
        coarse = self._powers(self._run([2] * self.code_count, project_path=directory / "pilot_coarse.fsp"))
        refined = dict(self.physics)
        refined["mesh_xy_m"] *= 0.75
        refined["mesh_z_m"] *= 0.75
        refined["metal_mesh_divisions"] = 4
        refined["simulation_time_s"] *= 2
        fine_solver = LumericalSolver(refined, self.rectangle_fn, self.code_count)
        fine_solver.directory = directory
        print("Preflight: refined reference", flush=True)
        fine_solver.reference = fine_solver._run([0] * 4, "empty")
        print("Preflight: refined pilot", flush=True)
        fine = fine_solver._powers(fine_solver._run([2] * 4, project_path=directory / "pilot_refined.fsp"))
        error = max(np.max(abs(coarse[key] - fine[key])) for key in ("co", "total"))
        if error > self.physics["convergence_power_tolerance"]:
            raise RuntimeError(f"Pilot mesh/time convergence failed: maximum power difference {error:.4g}.")
        record = {**raw, "physics": np.asarray(signature), "passed": np.asarray(True),
                  "convergence_error": np.asarray(error), "coarse_co": coarse["co"], "fine_co": fine["co"]}
        save_npz(path, record)
        print(f"Preflight: passed and saved, power difference {error:.4g}", flush=True)
        self.reference = record

    def simulate(self, codes, frequencies):
        """Simulate one device using the accepted reference normalization.

        Args:
            codes (array-like): Four independent pattern IDs.
            frequencies (array-like): Frequency grid requested by generation.
        Returns:
            dict: Co-polarized, cross-polarized, and total reflected power.
        Raises:
            RuntimeError: If the solver or acceptance gates fail.
            ValueError: If the requested grid differs from the simulated grid.
        """
        raw = self._run(codes)
        if not np.allclose(raw["frequencies"], frequencies, rtol=1e-8):
            raise ValueError("Requested frequency grid differs from simulation.")
        return self._powers(raw)
